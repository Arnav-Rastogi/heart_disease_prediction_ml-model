"""Create a compact PDF summary for a prediction result."""

from __future__ import annotations

from io import BytesIO
from typing import Any, Mapping

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle


def build_pdf_report(patient: Mapping[str, Any], result: Mapping[str, Any]) -> bytes:
    """Build a downloadable patient-input and model-output report."""
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=0.7 * inch, leftMargin=0.7 * inch,
                            topMargin=0.65 * inch, bottomMargin=0.65 * inch)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="BrandTitle", parent=styles["Title"], textColor=colors.HexColor("#10243a"),
                              alignment=TA_CENTER, fontSize=22, spaceAfter=5))
    styles.add(ParagraphStyle(name="Disclaimer", parent=styles["BodyText"], textColor=colors.HexColor("#536174"),
                              fontSize=9, leading=13))
    story = [Paragraph("CardioPredict AI", styles["BrandTitle"]),
             Paragraph("Heart health prediction summary", styles["Heading2"]), Spacer(1, 12)]
    label = "Elevated model risk estimate" if result["prediction"] == 1 else "Lower model risk estimate"
    data = [["Model output", label], ["Estimated heart disease probability", f"{result['probability_disease']:.1%}"],
            ["Estimated no-disease probability", f"{result['probability_no_disease']:.1%}"]]
    table = Table(data, colWidths=[3.1 * inch, 3.5 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#10243a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#f2f5f9")),
        ("TEXTCOLOR", (0, 1), (-1, -1), colors.HexColor("#10243a")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#dce3ec")),
        ("PADDING", (0, 0), (-1, -1), 9),
    ]))
    story.extend([table, Spacer(1, 20), Paragraph("Patient inputs", styles["Heading2"])])
    summary = [["Input", "Value"]] + [[str(key), str(value)] for key, value in patient.items()]
    details = Table(summary, colWidths=[3.1 * inch, 3.5 * inch], repeatRows=1)
    details.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8edf4")),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#10243a")),
        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#dce3ec")),
        ("PADDING", (0, 0), (-1, -1), 7),
    ]))
    story.extend([details, Spacer(1, 18), Paragraph(
        "This report is generated by a machine learning model for educational and informational purposes. "
        "It is not a medical diagnosis, does not replace professional medical advice, and should not be used "
        "to make healthcare decisions. Please consult a qualified healthcare professional.", styles["Disclaimer"]),
        Spacer(1, 8), Paragraph("Model: Logistic Regression · Original project test accuracy: 86.8%", styles["Disclaimer"])])
    doc.build(story)
    return buffer.getvalue()

